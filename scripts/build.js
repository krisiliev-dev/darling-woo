#!/usr/bin/env node
/* =============================================================================
   build.js  -  the one command.

   *** EVERY OUTPUT IN THIS REPO IS DERIVED FROM theme/darling/src/, AND EVERY
   ONE OF THEM CAN BE FORGOTTEN. *** That is the whole reason this exists. The
   stylesheet, theme.json, the Stripe appearance object, the category banners,
   the resolved token table and the gallery are six artefacts generated by six
   scripts, and a person who edits a token and runs five of them has shipped a
   checkout whose card fields are the old colour. Nobody notices for a month,
   because the only place it shows is inside an iframe.

   So there is one command, it knows the order, and the order lives here and
   nowhere else:

     node scripts/build.js            build everything that is out of date
     node scripts/build.js --watch    and keep doing it as src/ changes
     node scripts/build.js --force    ignore the cache, rebuild the lot

   *** ON THE BOX: ENABLE A CRON FOR THE WATCHER AT CUTOVER. ***
   Nothing schedules this yet. It is a laptop-side convenience today and the
   day the theme is deployed it has to become a real job on the server, or the
   first person to edit a token over SSH ships a stylesheet that disagrees with
   theme.json and a Stripe appearance object nobody regenerated.

   The RIGHT answer on a server is a deploy step - build once, on push, before
   the files are live - because a watcher on a production box rebuilds at
   whatever moment somebody happens to save, which is not a moment anybody
   chose. The cron is the belt to that braces: it catches an edit made directly
   on the box, which is exactly the edit nobody remembers.

     (the crontab line is below this comment block, in line comments - a
     schedule that starts with a star and a slash cannot live inside a C-style
     comment, which is how this file came to be a syntax error for an hour)

   build.js is already safe to run on a timer: it skips the browser step when
   src/tokens is unchanged, so an idle run is under three seconds and writes
   byte-identical output.

   If a watcher is wanted instead of a timer, it is the same command with
   --watch under systemd rather than cron - Restart=always, and it must NOT run
   as root.

   *** THE ORDER IS NOT ARBITRARY AND IS WORTH READING. ***
   gen-category-banners writes INTO src/, so it must run before anything reads
   src/. resolve-tokens needs the BUILT stylesheet, because the only honest way
   to resolve color-mix(in oklab, ...) is to ask a browser. gen-stripe needs the
   resolved table. gen-gallery needs the built stylesheet and the shim. Get this
   wrong and the build succeeds while shipping the previous run's output - which
   already happened once with the banners.

   *** WHAT IS SKIPPED, AND WHY THAT IS SAFE. ***
   resolve-tokens launches a real Chromium, which is three or four seconds - too
   slow to run on every keystroke in watch mode. It only matters when a TOKEN
   changes, so the tokens directory is hashed and the step is skipped when the
   hash is unchanged. Everything else runs every time, because everything else
   is milliseconds and a stale artefact is worse than a slow build. --force
   ignores the cache.
   ========================================================================== */
// -- the cron line, in line comments so its leading `*` + `/` is harmless -----
// # /etc/cron.d/darling-build   - every 15 minutes; an idle run is a no-op
// */15 * * * * www-data cd /srv/darling/darling-woo && node scripts/build.js >> /var/log/darling-build.log 2>&1
//
// Owned by www-data, not root. www-data must own theme/darling/generated/ and
// scripts/.build-cache.json or the first run fails on a permission error that
// nobody sees, because cron mails it to a local mailbox nobody reads.

'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'theme', 'darling', 'src');
const CACHE = path.join(ROOT, 'scripts', '.build-cache.json');

const argv = process.argv.slice(2);
const WATCH = argv.includes('--watch') || argv.includes('-w');
const FORCE = argv.includes('--force') || argv.includes('-f');

/* ---------------------------------------------------------------- helpers -- */
function hashDir(dir) {
	if (!fs.existsSync(dir)) return '';
	const h = crypto.createHash('sha1');
	for (const f of fs.readdirSync(dir).sort()) {
		const p = path.join(dir, f);
		if (fs.statSync(p).isDirectory()) { h.update(hashDir(p)); continue; }
		h.update(f).update(fs.readFileSync(p));
	}
	return h.digest('hex');
}
function readCache() {
	try { return JSON.parse(fs.readFileSync(CACHE, 'utf8')); } catch (e) { return {}; }
}
function writeCache(c) {
	try { fs.writeFileSync(CACHE, JSON.stringify(c, null, 1)); } catch (e) {}
}
function node(script) {
	execFileSync(process.execPath, [path.join(__dirname, script)], { stdio: 'inherit', cwd: ROOT });
}
/* Python is looked up by name rather than assumed, and its absence is a SKIP
   and not a failure: the gallery is documentation, and documentation must never
   be able to break a stylesheet build. */
function python(script) {
	for (const py of ['python3', 'python', 'py']) {
		try {
			execFileSync(py, [path.join(__dirname, script)], { stdio: 'inherit', cwd: ROOT });
			return true;
		} catch (e) {
			if (e.status !== undefined) throw e;   /* it ran and failed - that is real */
		}
	}
	console.log('   (no python on PATH - skipped ' + script + ')');
	return false;
}

/* ------------------------------------------------------------------ steps -- */
const STEPS = [
	{ name: 'category banners', run: () => node('gen-category-banners.js'),
	  why: 'writes into src/, so it goes first' },
	{ name: 'stylesheet',       run: () => node('build-css.js'),
	  why: 'concat, layer wrap, token check' },
	{ name: 'theme.json',       run: () => node('gen-theme-json.js'),
	  why: 'the block editor reads this, not the CSS' },
	{ name: 'resolved tokens',  run: () => node('resolve-tokens.js'),
	  why: 'needs a browser to resolve oklab', tokensOnly: true },
	{ name: 'stripe appearance', run: () => node('gen-stripe-appearance.js'),
	  why: 'the card iframe cannot read a token', tokensOnly: true },
	{ name: 'gallery',          run: () => python('gen-gallery.py'),
	  why: 'the picture of the system' },
	/* NEXT ONES GO HERE, and they are the reason this file exists rather than a
	   list in somebody's head:
	     gen-email-css.js   - WooCommerce emails, resolved hex, no custom props
	     gen-print-css.js   - order-received, print-color-adjust
	     audit-forced-colors.js / audit-rtl.js - gates, not generators */
];

function build(reason) {
	const t0 = Date.now();
	const cache = readCache();
	const tokenHash = hashDir(path.join(SRC, 'tokens'));
	const tokensChanged = FORCE || cache.tokens !== tokenHash;

	console.log('\n=== darling build' + (reason ? '  (' + reason + ')' : '') +
		(tokensChanged ? '' : '   [tokens unchanged]'));
	for (const s of STEPS) {
		if (s.tokensOnly && !tokensChanged) {
			console.log('-- ' + s.name + ': skipped, tokens unchanged');
			continue;
		}
		console.log('-- ' + s.name);
		try {
			s.run();
		} catch (e) {
			console.error('\n*** BUILD FAILED at "' + s.name + '" ***');
			if (!WATCH) process.exit(1);
			return;
		}
	}
	cache.tokens = tokenHash;
	writeCache(cache);
	console.log('=== done in ' + ((Date.now() - t0) / 1000).toFixed(1) + 's');
}

/* ------------------------------------------------------------------ watch -- */
function watch() {
	const targets = [
		SRC,
		path.join(ROOT, 'theme', 'darling', 'assets', 'img', 'banners'),
		path.join(ROOT, 'theme', 'darling', 'assets'),
	].filter(p => fs.existsSync(p));

	let timer = null, pending = new Set();
	const bounce = (f) => {
		/* src/generated/ is written BY the build, so watching it would make the
		   build trigger itself forever. Same for the built stylesheet and the
		   gallery, which is why only src/ and the two asset folders are here. */
		if (!f || f.includes('generated')) return;
		if (!/\.(css|js|webp|png|jpe?g|svg|json)$/i.test(f)) return;
		pending.add(f);
		clearTimeout(timer);
		timer = setTimeout(() => {
			const list = [...pending].slice(0, 3).join(', ') + (pending.size > 3 ? ' +' + (pending.size - 3) : '');
			pending.clear();
			build(list);
		}, 250);
	};

	for (const t of targets) {
		try { fs.watch(t, { recursive: true }, (_e, f) => bounce(f)); }
		catch (e) { fs.watch(t, (_e, f) => bounce(f)); }
	}
	console.log('watching:\n  ' + targets.map(t => path.relative(ROOT, t)).join('\n  '));
	console.log('  (ctrl-c to stop)');
}

build(FORCE ? 'forced' : null);
if (WATCH) watch();