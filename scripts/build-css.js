/**
 * build-css.js - concatenate src/ into one stylesheet.
 *
 * WHY A SCRIPT AND NOT @import: there is no build step in this repo and native
 * @import costs a blocking round trip per file, serialised - an @import inside
 * an imported file cannot even begin until its parent has arrived. Eight files
 * would be eight sequential requests before first paint, on an audience that is
 * mostly mid-range Android. So src/ is for authoring and one file ships.
 *
 * No dependencies. Run: node scripts/build-css.js
 *
 * It reads the @import lines out of src/index.css IN ORDER, so the import list
 * there stays the single place the file order is declared. A file that is not
 * imported is not built - which is the point.
 */
/* The banner rules are generated from the images on disk and then CONCATENATED
   like any other src file, so this has to run before anything is read - not at
   the end with the other generators. Run it there and the build ships the
   PREVIOUS run's banners, which on a fresh clone is none at all. */
require('./gen-category-banners.js');
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'theme', 'darling', 'src');
const OUT = path.join(__dirname, '..', 'theme', 'darling', 'darling.build.css');

const entry = fs.readFileSync(path.join(SRC, 'index.css'), 'utf8');

// keep the @layer statement, drop the @import lines, remember their order
const layerLine = (entry.match(/^@layer[^;]*;/m) || [''])[0];
const imports = [...entry.matchAll(/@import\s+url\(["']([^"']+)["']\)\s*(?:layer\(([^)]*)\))?\s*;/g)]
  .map((m) => ({ file: m[1], layer: m[2] || null }));

let out = '/* GENERATED by scripts/build-css.js - do not edit. Author in src/. */\n';
if (layerLine) out += layerLine + '\n\n';

let missing = 0;
for (const im of imports) {
  const p = path.join(SRC, im.file);
  if (!fs.existsSync(p)) { console.log('MISSING ' + im.file); missing++; continue; }
  const body = fs.readFileSync(p, 'utf8');
  out += '\n/* ==== ' + im.file + ' ==== */\n';
  // a file that already declares its own @layer block is passed through as-is;
  // otherwise it is wrapped in the layer the import asked for.
  if (im.layer && !/^\s*@layer\s+[a-z-]+\s*\{/m.test(body)) {
    out += '@layer ' + im.layer + '{\n' + body + '\n}\n';
  } else {
    out += body + '\n';
  }
}

fs.writeFileSync(OUT, out);
const kb = (Buffer.byteLength(out) / 1024).toFixed(1);
console.log('built ' + path.basename(OUT) + '  ' + kb + ' KB  from ' + imports.length + ' file(s)' +
            (missing ? '  (' + missing + ' MISSING)' : ''));
// Fail the build on a token that is referenced but never declared. See the
// file for why this is not optional.
require('./check-tokens.js');


// theme.json is generated from the same tokens, so the editor's palette and the
// stylesheet can never drift apart.
require('./gen-theme-json.js');

/* *** EVERY NON-CSS CONSUMER IS GENERATED FROM THE SAME src/, OR IT DRIFTS. ***
   theme.json was the first. The Stripe appearance object is the second, and it
   is the one that matters most: the card fields are in a cross-origin iframe,
   so they are the only surface on the checkout that cannot read a token. Hand
   written, they go stale silently - every field moves when --edge-field changes
   except the three that take the money.

   resolve-tokens needs a real browser (color-mix in oklab is not something to
   reimplement in node), so it is async and the generator runs after it. If
   playwright is not installed the build still succeeds and says what it skipped
   rather than failing a CSS build over a downstream artefact. */
(async () => {
  try {
    require.resolve('playwright');
  } catch (e) {
    console.log('  (playwright absent - skipped resolve-tokens + gen-stripe-appearance)');
    return;
  }
  const { execFileSync } = require('child_process');
  const path = require('path');
  for (const s of ['resolve-tokens.js', 'gen-stripe-appearance.js']) {
    execFileSync(process.execPath, [path.join(__dirname, s)], { stdio: 'inherit' });
  }

  /* *** THE GALLERY IS PART OF THE BUILD, NOT A THING SOMEBODY REMEMBERS. ***
     A picture of the design system that has to be regenerated by hand is
     quietly wrong within a week - and a wrong gallery is worse than none,
     because people trust it. Change a token, run the build, and
     theme/darling/gallery.html is already correct.
     Python because that is what it is written in and the repo already runs
     .py scripts; if python is not on PATH the CSS build still succeeds and
     says what it skipped, because a documentation artefact must never be able
     to fail a stylesheet. */
  for (const py of ['python3', 'python', 'py']) {
    try {
      execFileSync(py, [path.join(__dirname, 'gen-gallery.py')], { stdio: 'inherit' });
      return;
    } catch (e) { /* try the next name */ }
  }
  console.log('  (no python on PATH - skipped gen-gallery)');
})();

