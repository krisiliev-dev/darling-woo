/**
 * build-css.js - concatenate src/ into one stylesheet.
 *
 * WHY A SCRIPT AND NOT @import: there is no build step in this repo and native
 * @import costs a blocking round trip per file, serialised - an @import inside
 * an imported file cannot even begin until its parent has arrived. Eight files
 * would be eight sequential requests before first paint, on an audience that is
 * mostly mid-range Android. So src/ is for authoring and one file ships.
 *
 * No dependencies. Run: node scripts/build-css.js
 *
 * It reads the @import lines out of src/index.css IN ORDER, so the import list
 * there stays the single place the file order is declared. A file that is not
 * imported is not built - which is the point.
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'theme', 'darling', 'src');
const OUT = path.join(__dirname, '..', 'theme', 'darling', 'darling.build.css');

const entry = fs.readFileSync(path.join(SRC, 'index.css'), 'utf8');

// keep the @layer statement, drop the @import lines, remember their order
const layerLine = (entry.match(/^@layer[^;]*;/m) || [''])[0];
const imports = [...entry.matchAll(/@import\s+url\(["']([^"']+)["']\)\s*(?:layer\(([^)]*)\))?\s*;/g)]
  .map((m) => ({ file: m[1], layer: m[2] || null }));

let out = '/* GENERATED by scripts/build-css.js - do not edit. Author in src/. */\n';
if (layerLine) out += layerLine + '\n\n';

let missing = 0;
for (const im of imports) {
  const p = path.join(SRC, im.file);
  if (!fs.existsSync(p)) { console.log('MISSING ' + im.file); missing++; continue; }
  const body = fs.readFileSync(p, 'utf8');
  out += '\n/* ==== ' + im.file + ' ==== */\n';
  // a file that already declares its own @layer block is passed through as-is;
  // otherwise it is wrapped in the layer the import asked for.
  if (im.layer && !/^\s*@layer\s+[a-z-]+\s*\{/m.test(body)) {
    out += '@layer ' + im.layer + '{\n' + body + '\n}\n';
  } else {
    out += body + '\n';
  }
}

/* *** BRACE BALANCE, PER FILE AND ON THE OUTPUT, BEFORE ANYTHING IS WRITTEN. ***
   An unbalanced brace does not fail loudly. This script wraps each file in
   `@layer <name>{ ... }`, so one stray `}` closes the layer early and hands the
   rest of the sheet to the browser's error recovery, which decides for itself
   which rules survive.
   It cost four rounds of debugging once: `.d-field--invalid .d-field__control`
   was present in the built CSS, matched its element according to
   element.matches(), sat in the right layer - and never reached the CSSOM,
   because a stray brace in footer.css three files earlier had ended the layer.
   Same argument as the undefined-property check below: silence is the problem.
   Comments are stripped first, because a brace in a comment is not a brace. */
const strip = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '');
const braces = (s) => [(s.match(/\{/g) || []).length, (s.match(/\}/g) || []).length];
const unbalanced = [];
for (const im of imports) {
  const p = path.join(SRC, im.file);
  if (!fs.existsSync(p)) continue;
  const [o, c] = braces(strip(fs.readFileSync(p, 'utf8')));
  if (o !== c) unbalanced.push('  ' + im.file + '   ' + o + ' open, ' + c + ' close');
}
/* *** RELATIVE url() IS A LIE IN THE BUILT SHEET. ***
   Authoring happens in theme/darling/src/; the build lands one directory up, at
   theme/darling/darling.build.css. So `url("../assets/x.webp")` - correct while
   you are reading the source file - resolves against the OUTPUT once built, to
   /wp-content/themes/assets/x.webp, a directory that holds every theme on the
   box and not our asset.
   It cost nothing for months because nothing loaded the built sheet. The first
   page load after the enqueue went live requested a missing grain texture 101
   times on the home page alone, and the only symptom was a console the size of
   a phone book. Every other url() in src/ is already absolute; this makes the
   convention a rule instead of a habit. */
const badUrl = [];
for (const im of imports) {
  const p = path.join(SRC, im.file);
  if (!fs.existsSync(p)) continue;
  const body = strip(fs.readFileSync(p, 'utf8'));
  for (const m of body.matchAll(/url\(\s*(["']?)([^"')]+)\1\s*\)/g)) {
    const u = m[2].trim();
    if (/^(data:|https?:|\/|#)/.test(u)) continue;
    badUrl.push('  ' + im.file + '   url(' + u + ')');
  }
}
if (badUrl.length) {
  console.error('\nRELATIVE url() IN src/ - these resolve from the BUILT sheet, one directory\n'
    + 'up, not from the file you wrote them in:\n' + badUrl.join('\n')
    + '\n\nWrite them absolute: url("/wp-content/themes/darling/assets/...").\n'
    + 'Nothing was written; the previous build is still on disk.\n');
  process.exit(1);
}
const [bo, bc] = braces(strip(out));
if (bo !== bc) unbalanced.push('  (built output)   ' + bo + ' open, ' + bc + ' close');
if (unbalanced.length) {
  console.error('\nBRACE BALANCE FAILED - a stray brace closes an @layer early and the\n'
    + 'browser then drops rules silently from that point on:\n'
    + unbalanced.join('\n') + '\n\nNothing was written; the previous build is still on disk.\n');
  process.exit(1);
}

fs.writeFileSync(OUT, out);
const kb = (Buffer.byteLength(out) / 1024).toFixed(1);
console.log('built ' + path.basename(OUT) + '  ' + kb + ' KB  from ' + imports.length + ' file(s)' +
            (missing ? '  (' + missing + ' MISSING)' : ''));
// Fail the build on a token that is referenced but never declared. See the
// file for why this is not optional.
require('./check-tokens.js');


