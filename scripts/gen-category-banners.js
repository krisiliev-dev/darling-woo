/* =============================================================================
   gen-category-banners.js
   The banners folder -> src/generated/category-banners.css

   *** 28 RULES OF CONTENT WERE LIVING IN A STYLESHEET. ***
   style.css carried, once per category and then again inside a 700px query:
     body.tax-product_cat.term-za-kuhnyata .darling-cat-banner .dcb-img{
       background-image:image-set(
         url(.../za-kuhnyata-800.webp)  type("image/webp") 1x,
         url(.../za-kuhnyata-1400.webp) type("image/webp") 2x,
         url(.../za-kuhnyata.jpg)       type("image/jpeg") 1x) }

   That is data, and keeping data in CSS has three costs we were already paying:
   adding a category means editing a stylesheet, renaming a term silently loses
   its banner, and nobody can tell by reading the file which images actually
   exist on disk. Two of those are invisible until a customer lands on the page.

   Now the FOLDER is the source of truth. A term gets a banner by having files
   named after it; a term with no files is reported at build time instead of
   rendering an empty claret box in production.

   Naming it expects, all optional except the base:
     <slug>.jpg | .png | .webp     the base image
     <slug>-800.webp               1x
     <slug>-1400.webp              2x
   plus `all` for the shop archive, which is not a term.
   ========================================================================== */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const DIR = path.join(ROOT, 'theme', 'darling', 'assets', 'img', 'banners');
const OUTDIR = path.join(ROOT, 'theme', 'darling', 'src', 'generated');
const OUT = path.join(OUTDIR, 'category-banners.css');
const URLBASE = '/wp-content/themes/darling/assets/img/banners';

const TYPE = { '.webp': 'image/webp', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png' };

if (!fs.existsSync(DIR)) {
  console.log('gen-category-banners: no banners directory - nothing to do');
  fs.mkdirSync(OUTDIR, { recursive: true });
  fs.writeFileSync(OUT, '/* GENERATED - no banners directory found. */\n');
  process.exit(0);
}

const files = fs.readdirSync(DIR).filter(f => TYPE[path.extname(f).toLowerCase()]);
const terms = {};
for (const f of files) {
  const ext = path.extname(f).toLowerCase();
  const stem = path.basename(f, ext);
  const m = stem.match(/^(.*?)-(800|1400|650|265)$/);
  const slug = m ? m[1] : stem;
  terms[slug] = terms[slug] || {};
  if (m) terms[slug][m[2]] = f; else terms[slug].base = f;
}

function imageSet(t, narrow) {
  const parts = [];
  const one = narrow ? (t['800'] || t['650'] || t['265']) : (t['800'] || t['650'] || t['265']);
  const two = narrow ? one : (t['1400'] || one);
  if (one) parts.push('url("' + URLBASE + '/' + one + '") type("' + TYPE[path.extname(one).toLowerCase()] + '") 1x');
  if (two && two !== one) parts.push('url("' + URLBASE + '/' + two + '") type("' + TYPE[path.extname(two).toLowerCase()] + '") 2x');
  if (t.base) parts.push('url("' + URLBASE + '/' + t.base + '") type("' + TYPE[path.extname(t.base).toLowerCase()] + '") 1x');
  return parts.length ? 'image-set(' + parts.join(', ') + ')' : null;
}

const wide = [], narrow = [];
const noBase = [];
for (const slug of Object.keys(terms).sort()) {
  const t = terms[slug];
  if (!t.base && !t['800']) { noBase.push(slug); continue; }
  /* `all` is the shop archive, which is a post-type archive and not a term. */
  const sel = slug === 'all'
    ? 'body.post-type-archive-product .d-catbanner__img'
    : 'body.tax-product_cat.term-' + slug + ' .d-catbanner__img';
  const w = imageSet(t, false), n = imageSet(t, true);
  if (w) wide.push(sel + '{ background-image:' + w + ' }');
  /* Only emit the narrow override when it differs - half the original 28 rules
     were a 700px query repeating the 1x source as the 2x source. */
  if (n && n !== w) narrow.push(sel + '{ background-image:' + n + ' }');
}

const out = [
  '/* GENERATED by scripts/gen-category-banners.js - DO NOT EDIT.',
  '   Source of truth is theme/darling/assets/img/banners/.',
  '   Add a category banner by adding <slug>.jpg (+ optional -800.webp, -1400.webp);',
  '   this file rebuilds with the stylesheet.',
  '',
  '   ' + Object.keys(terms).length + ' banners found, ' + wide.length + ' rules,',
  '   ' + narrow.length + ' narrow overrides (the hand-written version had 28 rules,',
  '   half of them a 700px query that repeated the 1x source as the 2x source).',
  '*/',
  ...wide,
  '',
  narrow.length ? '@media (max-width: 700px){' : '',
  ...narrow.map(r => '\t' + r),
  narrow.length ? '}' : '',
  '',
].filter(l => l !== '').join('\n');

fs.mkdirSync(OUTDIR, { recursive: true });
fs.writeFileSync(OUT, out);
console.log('gen-category-banners: %d banners -> %d rules, %d narrow overrides',
  Object.keys(terms).length, wide.length, narrow.length);
if (noBase.length) console.log('  NO USABLE IMAGE for: ' + noBase.join(', '));
console.log('  written to ' + path.relative(ROOT, OUT));