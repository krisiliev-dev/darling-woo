"""Generate theme/darling/src/finish.css.

The variance blocks are ~40 lines of coordinates. Typing them by hand is how a
transposed digit gets into a design system and never gets found, so they are
generated from a fixed table and the file is written whole. ASCII only: the
Windows shell that receives this file reads UTF-8 bytes as the ANSI codepage,
which is exactly how the last preview shipped with mojibake Cyrillic.
"""

# grain offsets - period 5 and 7, flip on 3
GRAIN_X = ['0%', '37%', '64%', '18%', '81%']
GRAIN_Y = ['0%', '43%', '71%', '12%', '88%', '29%', '56%']

# broad speculars - period 11. Kept in the middle band: a specular pinned to a
# corner reads as a mistake rather than as light.
FLAIRS = [
    (32, 37, 73, 69), (24, 30, 68, 74), (41, 28, 80, 62), (29, 44, 64, 58),
    (37, 33, 77, 71), (21, 39, 70, 66), (35, 26, 83, 73), (27, 35, 66, 61),
    (44, 41, 75, 76), (19, 32, 71, 64), (39, 47, 61, 70),
]

# flecks in the varnish - period 13, four per instance, scattered anywhere
SPECKS = [
    (18, 62, 55, 24, 86, 41, 41, 81), (73, 19, 12, 47, 60, 88, 34, 33),
    (47, 71, 90, 58, 26, 16, 66, 44), (31, 28, 78, 83, 14, 69, 57, 52),
    (64, 37, 23, 79, 92, 22, 45, 61), (11, 53, 69, 14, 38, 86, 83, 48),
    (52, 18, 88, 66, 20, 35, 61, 77), (80, 44, 36, 12, 15, 74, 70, 58),
    (25, 66, 59, 31, 94, 80, 43, 17), (67, 73, 17, 26, 48, 55, 87, 36),
    (39, 42, 82, 71, 29, 91, 54, 21), (75, 29, 44, 64, 13, 38, 63, 85),
    (56, 49, 28, 82, 71, 15, 91, 60),
]

# drift vectors - period 17, in px, one per speckle. Directions are scattered
# around the circle so no two neighbours drift the same way, and the amplitude
# is small: this is varnish catching light, not particles.
DRIFT = [
    ((4, -3), (-3, 4), (2, 5), (-5, -2)),   ((-4, 2), (5, 1), (-2, -5), (3, 4)),
    ((3, 5), (-5, -1), (4, -3), (-2, 3)),   ((-3, -4), (2, -5), (5, 2), (-4, 3)),
    ((5, 1), (-2, 4), (-4, -3), (3, -5)),   ((-5, 3), (4, -2), (1, 5), (-3, -4)),
    ((2, -5), (-4, -3), (5, 3), (-1, 4)),   ((-2, 4), (3, 5), (-5, -1), (4, -3)),
    ((4, 3), (-1, -5), (2, 4), (-5, 1)),    ((-4, -2), (5, -3), (-3, 5), (2, 2)),
    ((1, 5), (-5, 2), (4, -4), (-2, -3)),   ((-3, 4), (2, -4), (-5, 3), (5, -1)),
    ((5, -2), (-4, 4), (3, 3), (-1, -5)),   ((-1, -4), (4, 5), (-2, -3), (3, 2)),
    ((3, -4), (-5, -2), (1, 4), (-4, 5)),   ((-5, 1), (1, -4), (4, 2), (-3, -5)),
    ((2, 3), (-2, 5), (-4, -4), (5, -2)),
]

# per-instance rhythm - period 19, coprime to everything above
CYCLES = ['13s', '17s', '11s', '19s', '15s', '23s', '12s', '21s', '14s', '18s',
          '16s', '25s', '13.5s', '20s', '11.5s', '22s', '15.5s', '24s', '19.5s']
BREATHE = ['7s', '9s', '8s', '11s', '7.5s', '10s', '8.5s', '12s', '9.5s', '6.5s',
           '10.5s', '13s', '7.2s', '11.5s', '8.8s', '9.2s', '6.8s', '12.5s', '10.2s']

SPECK_N = 4


def bp(sign):
    """the background-position list, with the speckles pushed one way or the other"""
    rows = ['\t\tcenter,',
            '\t\tvar(--flair-1-x) var(--flair-1-y),',
            '\t\tvar(--flair-2-x) var(--flair-2-y),']
    for i in range(1, SPECK_N + 1):
        end = ';' if i == SPECK_N else ','
        rows.append('\t\tcalc(var(--speck-%d-x) %s var(--sd-%d-x) * var(--drift-k)) '
                    'calc(var(--speck-%d-y) %s var(--sd-%d-y) * var(--drift-k))%s'
                    % (i, sign, i, i, sign, i, end))
    return '\n'.join(rows)


out = []
w = out.append

w('''/* =============================================================================
   FINISH - the amber ramp, its light, its glow, its drift, and the plywood grain.

   GENERATED by scripts/gen-finish.py. The variance tables are the input; edit
   them there, not here.

   NAMING. The owner chose Shperplat (plywood) as the texture; "metal" in the
   older files named the LIGHTING MODEL, not the material. Four layers, one
   object:
       the finish   an amber ramp as body tone + a rim that models the edge
       the glow     amber light thrown OUTWARD and pooled INWARD, breathing
       the light    broad speculars (flairs) and small flecks (speckles) that
                    drift, each instance in its own directions at its own pace
       the grain    plywood, as a GREYSCALE map, so it lends pattern and nothing
                    else and takes its colour from the ramp beneath

   *** CONTAINER QUERIES CANNOT SIZE ANY OF IT. MEASURED, DO NOT RETRY. ***
   container-type:inline-size applies inline-size containment, so an element
   stops taking its width from its contents. A shrink-to-fit button measured
   323px plain and 52px with container-type - it collapses to its padding - and
   its ::after resolved background-size:50cqi to 0px 0px. An inline wrapper is
   no better: it measured 0 wide. So everything that must scale with a component
   scales in `em`: font-size already tracks a component's scale without
   containment and needs no JavaScript. A component whose size does not follow
   its type - a divider with no text - sets --grain-size explicitly.

   *** THE FINISH IS NEVER APPLIED TO TEXT. ***
   There used to be a .d-finish--text that clipped the ramp to glyphs, and the
   live wordmark still uses it. The owner: "we shouldn't use the texture on
   text... it makes it hard to read." Removed here deliberately, not lost. The
   live wordmark has to be ported to plain --ink; do not reintroduce this.
   ========================================================================== */

@layer finish{

/* Registered so they can be ANIMATED and TRANSITIONED. An unregistered custom
   property has no type, so it interpolates discretely - the glow would jump at
   the midpoint instead of breathing, and the hover would snap. */
@property --glow-k{       syntax:"<number>"; inherits:true;  initial-value:1 }
@property --glow-base{    syntax:"<number>"; inherits:true;  initial-value:1 }
@property --glow-breathe{ syntax:"<number>"; inherits:false; initial-value:1 }
@property --glow-hover{   syntax:"<number>"; inherits:false; initial-value:1 }
@property --drift-k{      syntax:"<number>"; inherits:true;  initial-value:1 }

:root{
	--grain-src: url("../assets/ply-grain.webp");
	--grain-mask: radial-gradient(64% 190% at 50% 50%, transparent 0 26%, #000 86%);

	/* Body tone. Banding across a form is the reflection of a WIDE environment,
	   which is why it reads as cut out of something larger. */
	--surface-finish:
		radial-gradient(52% 120% at 26% 20%, var(--g-vanilla) 0%, var(--g-light) 36%, transparent 74%),
		linear-gradient(175deg, var(--g-light) 0%, var(--g-core) 58%, var(--g-shadow) 100%);
}

/* *** EVERYTHING THAT READS --glow-k IS DECLARED HERE, ON .d-finish, NOT ON
   :root. MEASURED - MOVING IT BACK BREAKS THE DIMMER SILENTLY. ***
   var() inside a custom property is substituted at the computed-value time of
   THAT custom property, on the element it is declared on. With --rim on :root,
   its var(--glow-k) resolves against :root and every element inherits a value
   with the number already baked in: four buttons at 0 / .5 / 1 / 1.6 measured
   byte-identical box-shadows, alpha .8 and .7 on all four. Declared here,
   substitution happens on the element, so the breathe animation and the hover
   both reach it. */
.d-finish{
	/* --glow-base is the knob a COMPONENT sets. The other two are the animation
	   and the pointer, and they multiply in. Setting --glow-k directly from
	   outside still wins over all three - that is the escape hatch. */
	--glow-base: 1;
	--glow-k: calc(var(--glow-base) * var(--glow-breathe) * var(--glow-hover));

	/* *** THE RIM DERIVES FROM THE THREE NUMBERS. *** On the live site it does
	   not - it is five hand-written hsl() values - so changing --gh/--gs/--gl
	   today retints the surface and leaves the rim amber, and the object comes
	   apart. This is the fix, not a transcription. */
	--rim:
		inset  0    0    0   1px hsl(var(--gh) calc(var(--gs) * 1%) calc(34% + var(--gl) * 1%) / calc(.55 * var(--glow-k))),
		inset  0    9px  16px -11px hsl(from var(--g-vanilla) h s l / calc(.90 * var(--glow-k))),
		inset  0  -11px  20px -11px hsl(from var(--g-deep)    h s l / calc(.80 * var(--glow-k))),
		inset  9px  0    18px -14px hsl(from var(--g-deep)    h s l / calc(.70 * var(--glow-k))),
		inset -9px  0    18px -14px hsl(from var(--g-deep)    h s l / calc(.70 * var(--glow-k)));

	/* -- the glow, inward and outward --------------------------------------
	   *** BOX-SHADOWS, NOT A PSEUDO-ELEMENT. THIS IS A BUG FIX. ***
	   v1 put the halo on ::before at inset:0 with z-index:-1, which is entirely
	   occluded by the element's own opaque background - the buttons shipped
	   with no glow at all. The winning file gets its halo by spilling ::before
	   to inset:-45%, but measured on live that made scrollWidth 1.45x
	   clientWidth on both amber buttons at all six viewports, and neither
	   overflow:clip nor overflow:hidden moves scrollWidth. A box-shadow never
	   contributes to scrollable overflow, so this is the glow AND the overflow
	   fix, and there is no third option worth trying.

	   The INNER glow is the light pooling just inside the edge - it is what
	   makes the object read as lit from within rather than merely lit. It is a
	   gradient on ::before, not an inset shadow, so that it can breathe for
	   free; see the animation note below. */
	--glow-inner: hsl(from var(--g-light) h s l / calc(.55 * var(--glow-k)));
	--glow-outer:
		0 0    0    1px  hsl(from var(--g-light) h s l / calc(.30 * var(--glow-k))),
		0 2px  10px -2px hsl(from var(--g-core)  h s l / calc(.55 * var(--glow-k))),
		0 6px  26px -6px hsl(from var(--g-core)  h s l / calc(.50 * var(--glow-k))),
		0 0    40px -6px hsl(from var(--g-light) h s l / calc(.42 * var(--glow-k)));

	--lift: 0 2px 0 rgb(0 0 0 / .22), 0 8px 18px rgb(0 0 0 / .22);

	/* -- flairs and speckles ------------------------------------------------
	   Two scales of highlight, and they are not the same thing.
	   FLAIRS are the broad speculars: percentage-sized, so they scale with the
	   shape, and they do NOT drift - a light source that wanders reads as a
	   mistake. SPECKLES are the small bright flecks in the varnish: em-sized,
	   so a badge gets small ones and a hero button gets large ones exactly like
	   the grain, and each one drifts in its own direction.
	   Both are drawn on ::before and both are masked with --grain-mask, so they
	   live in the padding and never sit on a word. */
	--flair-a: hsl(48 100% 96% / calc(.95 * var(--glow-k)));
	--flair-b: hsl(45 100% 88% / calc(.55 * var(--glow-k)));
	--speck:   hsl(48 100% 98% / calc(.85 * var(--glow-k)));

	position:relative;
	isolation:isolate;
	color:var(--ink);
	background-color:var(--g-core);
	background-image:var(--surface-finish);
	background-repeat:no-repeat;
	background-size:100% 100%;
	box-shadow:var(--rim), var(--glow-outer), var(--lift);

	transition: --glow-hover var(--dur-ui) var(--ease-float);
}

/* -- the light on the surface ---------------------------------------------
   z-index:0, NOT -1: a positioned pseudo-element behind an opaque background
   is invisible. Above the background, below ::after's grain, masked off the
   label.

   Every layer is positioned by background-position rather than by `at x y`
   inside the gradient, because a position inside a gradient function cannot be
   animated and a background-position list can. */
.d-finish::before{
	content:"";
	position:absolute;
	inset:0;
	z-index:0;
	border-radius:inherit;
	pointer-events:none;
	background-image:
		radial-gradient(closest-side, transparent 52%, var(--glow-inner) 100%),
		radial-gradient(closest-side circle at center, var(--flair-a) 0%, var(--flair-b) 34%, transparent 100%),
		radial-gradient(closest-side circle at center, var(--flair-a) 0%, var(--flair-b) 26%, transparent 100%),
		radial-gradient(closest-side circle at center, var(--speck) 0%, transparent 100%),
		radial-gradient(closest-side circle at center, var(--speck) 0%, transparent 100%),
		radial-gradient(closest-side circle at center, var(--speck) 0%, transparent 100%),
		radial-gradient(closest-side circle at center, var(--speck) 0%, transparent 100%);
	background-size:
		100% 100%, 62% 150%, 46% 118%,
		.34em .34em, .24em .24em, .28em .28em, .20em .20em;
	background-repeat:no-repeat;
	background-position:
''' + bp('+') + '''
	-webkit-mask-image:var(--grain-mask);
	        mask-image:var(--grain-mask);
	-webkit-mask-size:100% 100%;
	        mask-size:100% 100%;

	/* LONGHANDS, not the shorthand: a component that needs its own animation
	   appends to animation-name rather than fighting a shorthand that would
	   reset duration and easing underneath it. */
	animation-name: d-speck-drift, d-finish-breathe;
	animation-duration: var(--speck-cycle, 15s), var(--breathe-cycle, 9s);
	animation-timing-function: var(--ease-float), var(--ease-float);
	animation-iteration-count: infinite, infinite;
}

/* -- the grain -------------------------------------------------------------
   Masked to the rim and the padding: clean where a label sits, grain in the
   space around it. Every value in the mask is a PERCENTAGE and mask-size is
   100% 100%, so it follows any shape - pill, circle, rounded square - with no
   fixed geometry and no script. The grain does NOT drift: plywood is the
   material, and material does not move. */
.d-finish::after{
	content:"";
	position:absolute;
	inset:0;
	z-index:1;
	border-radius:inherit;
	pointer-events:none;
	background-image:var(--grain-src);
	background-size:var(--grain-size, 17em) var(--grain-size, 17em);
	background-position:var(--grain-x, 0%) var(--grain-y, 0%);
	mix-blend-mode:overlay;
	-webkit-mask-image:var(--grain-mask);
	        mask-image:var(--grain-mask);
	-webkit-mask-size:100% 100%;
	        mask-size:100% 100%;
}

/* -- the pointer -----------------------------------------------------------
   Owner: "upon hovering an element, the glow of it and the speckles can become
   brighter and the speckles can be faster."
   Brightness transitions, because --glow-hover is registered. Speed does not:
   changing animation-duration re-derives the phase, so it steps rather than
   ramps. That step is under the cursor and reads as the object waking up, so
   it is left as a step rather than papered over with a second animation. */
.d-finish:hover,
.d-finish:focus-visible{
	--glow-hover: 1.34;
}
.d-finish:hover::before,
.d-finish:focus-visible::before{
	animation-duration: calc(var(--speck-cycle, 15s) * .34);
}

/* -- the two animations ----------------------------------------------------
   *** var() DOES NOT WORK FOR animation-timing-function INSIDE @keyframes. ***
   Measured: sampled 10% into a 4s cycle, a var() easing sat at 52.38px, exactly
   equal to linear, while the literal gave 53.55. It is silently dropped. So the
   easing lives on the element (where var() is fine) and never in here.

   var() in a normal property inside a keyframe IS fine, and is what makes these
   two keyframe blocks serve 255255 distinct instances. */
/* *** THE BREATHE IS AN OPACITY, NOT --glow-k. MEASURED, AND THE GAP IS LARGE. ***
   The obvious construction animates --glow-k, which is honest and reads well and
   costs the page. Chromium, 57 finished elements, 2.5s samples against a 60 fps
   baseline in the same browser:

       nothing animating .......................... 60 fps
       drift only (background-position) ........... 23
       breathe via --glow-k (4 shadow groups) ..... 15
       same, with the outer glow held static ...... 16
       breathe via opacity on ::before ............ 60
       opacity breathe AND drift together ......... 53

   Animating --glow-k re-resolves every relative-colour hsl() in four box-shadow
   groups and repaints a 40px blur on every element every frame, and holding the
   outer glow static recovered one frame, so it is the whole shadow stack, not
   the halo. Opacity on a pseudo-element is composited and costs nothing.

   Scaling with the opacity version: 60 fps to 36 elements, 52 at 57. A page with
   more than ~36 finished elements in view should set --breathe-cycle to 0s on
   the dense ones rather than hope.

   What this trades away: the OUTER halo no longer breathes, only the light on
   and inside the object. .d-finish--hero below buys that back for the one or two
   elements where it is worth a repaint. */
@keyframes d-finish-breathe{
	0%, 100% { opacity: .74 }
	42%      { opacity: 1 }
}

/* -- the hero exception ----------------------------------------------------
   The full-fat version: the outer halo breathes too, because --glow-k itself is
   animated. Costs a whole-shadow repaint per frame per element, so this is for
   the ONE object a page is built around - the main banner button - and it is
   opt-in for exactly that reason. Two elements is free; thirty is 15 fps. */
.d-finish--hero{
	animation-name: d-finish-breathe-glow;
	animation-duration: var(--breathe-cycle, 9s);
	animation-timing-function: var(--ease-float);
	animation-iteration-count: infinite;
}
@keyframes d-finish-breathe-glow{
	0%, 100% { --glow-breathe: .84 }
	42%      { --glow-breathe: 1.12 }
}

@keyframes d-speck-drift{
	0%, 100% { background-position:
''' + bp('-') + '''
	}
	50% { background-position:
''' + bp('+') + '''
	}
}
''')

w('''
/* -- NO TWO PIECES CUT FROM THE SAME SHEET ---------------------------------
   The owner, in order: "nowhere does it say they were cut from the same
   plywood"; then "another thing we can randomise along with the texture is the
   flairs and speckles on them"; then "they should move in a random direction."
   So five independent things vary, not one.

   CSS has no random(). These cycle on nth-of-type with COPRIME periods, so the
   combination repeats only at their product:

       grain offset    5 x 7            35
       grain flip      3               105
       flairs         11              1155
       speckles       13             15015
       drift + pace   17 x 19      4849845

   Four point eight million distinct finishes before any pair repeats, and every
   one is deterministic - no script, no flash on load, no layout shift, nothing
   on the money path.

   The individual vars remain the escape hatch: whatever renders a component can
   emit a real per-instance seed and it will win over all of these. */''')

for i, v in enumerate(GRAIN_X, 1):
    w('.d-finish:nth-of-type(5n+%d){ --grain-x: %s }' % (i, v))
for i, v in enumerate(GRAIN_Y, 1):
    w('.d-finish:nth-of-type(7n+%d){ --grain-y: %s }' % (i, v))
w('.d-finish:nth-of-type(3n)::after{ transform:scaleX(-1) }')

w('\n/* flairs on 11 - the light source shifts, so no two neighbours catch it the\n'
  '   same way. */')
for i, (ax, ay, bx, by) in enumerate(FLAIRS, 1):
    w('.d-finish:nth-of-type(11n+%-2d){ --flair-1-x:%d%%; --flair-1-y:%d%%; --flair-2-x:%d%%; --flair-2-y:%d%% }'
      % (i, ax, ay, bx, by))

w('\n/* speckle positions on 13 - scattered across the whole box, because unlike the\n'
  '   flairs they are meant to look like the material, not like the light. */')
for i, s in enumerate(SPECKS, 1):
    parts = ' '.join('--speck-%d-x:%d%%; --speck-%d-y:%d%%;' % (j + 1, s[2 * j], j + 1, s[2 * j + 1])
                     for j in range(SPECK_N))
    w('.d-finish:nth-of-type(13n+%-2d){ %s }' % (i, parts.rstrip(';')))

w('\n/* drift vectors on 17 - each speckle in its own direction, small amplitude. */')
for i, d in enumerate(DRIFT, 1):
    parts = ' '.join('--sd-%d-x:%dpx; --sd-%d-y:%dpx;' % (j + 1, d[j][0], j + 1, d[j][1])
                     for j in range(SPECK_N))
    w('.d-finish:nth-of-type(17n+%-2d){ %s }' % (i, parts.rstrip(';')))

w('\n/* pace on 19 - drift cycle and breathe cycle, so neighbours never sync up. */')
for i, (c, b) in enumerate(zip(CYCLES, BREATHE), 1):
    w('.d-finish:nth-of-type(19n+%-2d){ --speck-cycle:%s; --breathe-cycle:%s }' % (i, c, b))

w('''
/* -- the kill switches are in motion.css and are blanket -------------------
   `*, *::before, *::after { animation:none !important }` under reduced motion,
   and the same for `*, *::before` on cart / checkout / order-received. Both
   already catch everything above; nothing here needs its own opt-out.

   GAP, FOUND WHILE WRITING THIS: the money-path rule lists `*` and `*::before`
   but not `*::after`. Harmless today because ::after carries only the static
   grain, but the next animated ::after on a checkout page will run. Fix belongs
   in motion.css. */
}''')

text = '\n'.join(out) + '\n'
assert all(ord(c) < 128 for c in text), 'non-ascii leaked into the generated file'
open('/home/claude/finish.css', 'w', encoding='ascii').write(text)
print('wrote finish.css', len(text), 'bytes,',
      text.count('.d-finish:nth-of-type'), 'variance rules')
